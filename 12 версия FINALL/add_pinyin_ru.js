for (let lid = 1; lid <= 20; lid++) {
  const dialogues = D[lid];
  if (!dialogues) continue;
  out += `${lid}:[`;
  
  dialogues.forEach((d, di) => {
    const origTitle = titles[ti] ? titles[ti].title : d.title;
    ti++;
    
    if (d.type === "reading") {
      out += `{title:"${origTitle}",type:"reading",text:"${esc(d.text)}",pinyin:"${esc(d.pinyin)}",ru:"${esc(d.ru)}"}`;
    } else {
      out += `{title:"${origTitle}",type:"dialogue",lines:[`;
      d.lines.forEach((ln, li) => {
        const spPy = speakerPy[ln.s] || '';
        out += `{speaker:"${ln.s}",speakerPy:"${esc(spPy)}",text:"${esc(ln.t)}",pinyin:"${esc(ln.py)}",ru:"${esc(ln.ru)}"}`;
        if (li < d.lines.length - 1) out += ",";
      });
      out += "]}";
    }
    if (di < dialogues.length - 1) out += ",";
  });
  
  out += ",\n";
}
